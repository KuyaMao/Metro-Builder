"""Packs tex/*.jpg into game/texpack.js (data URLs, so the game stays a single offline file)."""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'game/tex'
items = []
for f in sorted(src.glob('*.jpg')):
    items.append(f'"{f.stem}":"data:image/jpeg;base64,{base64.b64encode(f.read_bytes()).decode()}"')
(root / 'game/texpack.js').write_text('/* Metro Builder material textures (original, generated by tools/gen_textures.py) */\nwindow.TEXPACK={' + ',\n'.join(items) + '};\n')
print('texpack', (root / 'game/texpack.js').stat().st_size // 1024, 'KB')
